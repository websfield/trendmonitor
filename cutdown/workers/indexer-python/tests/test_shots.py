"""Shot sub-stage tests (Phase 2 task 3) — PRD REQ-012, decisions.md D-18.

The behaviours proved here are the ones that lose footage or corrupt downstream
sub-stages when they break:

* shots TILE the asset — a gap is footage no Moment can ever reference again;
* `keyframeTicks` is strictly inside its own shot — OCR reading the next shot's
  first frame would attribute its text to the wrong shot;
* a static take still produces shots — zero shots starves OCR, one asset-long
  shot compresses the whole clip into a single keyframe;
* ticks come from the container timebase, never an averaged fps — `ugly.mp4` is
  genuinely VFR and an fps guess places every boundary wrong;
* every threshold reaches the index — REQ-012 says recorded, so it is asserted.

Fixture provenance is `cutdown/skills/index/fixtures/shots/README.md`; the three
transition clips were generated by ffmpeg because none of the ingest golden-set
media contains a detectable cut, fade or camera move (verified: all three
detectors return an empty list on `clean.mp4`, `ugly.mp4` and `broll-silent.mp4`).
"""

