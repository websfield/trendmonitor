class TestDetectionOnRealMedia:
    """Positive fixture per transition kind, each with the others as controls."""

    def test_hard_cuts_are_detected_and_labelled(self) -> None:
        shots = shots_for(HARD_CUT_MP4)
        assert len(shots) == 3, "three solid-colour segments, two cuts"
        assert shots[0]["transitionOut"] == "hard_cut"
        assert shots[1]["transitionIn"] == "hard_cut"

    def test_the_hard_cut_fixture_reports_no_fade(self) -> None:
        # Negative control: the clip never goes to black, so a `fade` here would
        # mean ThresholdDetector is firing on content rather than luma.
        shots = shots_for(HARD_CUT_MP4)
        transitions = {s["transitionIn"] for s in shots} | {s["transitionOut"] for s in shots}
        assert "fade" not in transitions

    def test_a_fade_to_black_is_labelled_fade_not_hard_cut(self) -> None:
        shots = shots_for(FADE_MP4)
        transitions = {s["transitionIn"] for s in shots} | {s["transitionOut"] for s in shots}
        assert "fade" in transitions
        assert "hard_cut" not in transitions, "precedence must keep a fade from reading as a cut"

    def test_a_camera_move_is_labelled_camera_change_not_hard_cut(self) -> None:
        shots = shots_for(CAMERA_CHANGE_MP4)
        transitions = {s["transitionIn"] for s in shots} | {s["transitionOut"] for s in shots}
        assert "camera_change" in transitions
        assert "hard_cut" not in transitions, "a continuous pan is not a cut"

    def test_a_static_take_falls_back_to_time_slices(self) -> None:
        # broll-silent.mp4 is one frozen frame: every detector correctly returns
        # nothing, and the fallback is the only thing standing between OCR and
        # an empty input.
        shots = shots_for(BROLL_MP4)
        assert len(shots) >= 2
        assert all(s["transitionIn"] == "unknown" and s["transitionOut"] == "unknown" for s in shots)
        assert_tiles(shots, 61440)

    def test_every_fixture_tiles_its_asset(self) -> None:
        for media in (HARD_CUT_MP4, FADE_MP4, CAMERA_CHANGE_MP4, CLEAN_MP4, UGLY_MP4, BROLL_MP4):
            assert_tiles(shots_for(media), probe_video(media).duration_ticks)

    def test_detection_is_byte_identical_across_runs(self) -> None:
        # Contract §5. PySceneDetect is deterministic given the same decode, so a
        # difference here would mean we introduced the non-determinism.
        assert canonical_json(compute_shots(FADE_MP4)) == canonical_json(compute_shots(FADE_MP4))


class TestVariableFrameRate:
    """`ugly.mp4` is genuinely VFR: average 400/19 fps, container timebase 1/15360."""

    def test_the_average_frame_rate_really_does_disagree_with_the_timebase(self) -> None:
        # Guards the premise of every other test in this class: if this fixture
        # were secretly CFR, the VFR assertions below would pass vacuously.
        result = probe_video(UGLY_MP4)
        assert result.avg_frame_rate == Fraction(400, 19)
        assert result.avg_frame_rate != Fraction(result.timebase.den, result.timebase.num)

    def test_ticks_are_in_the_container_timebase_not_the_average_frame_rate(self) -> None:
        shots = compute_shots(UGLY_MP4)["shots"]
        assert all(s["timebase"] == {"num": 1, "den": 15360} for s in shots)
        # 19/400 would be the timebase if we had assumed the average frame rate
        # was the real one — the exact mistake this asserts against.
        assert all(s["timebase"] != {"num": 19, "den": 400} for s in shots)

    def test_the_last_shot_ends_on_the_exact_asset_duration(self) -> None:
        shots = compute_shots(UGLY_MP4)["shots"]
        # 58368 / 15360 == 3.8 s exactly. Reconstructing the duration from
        # frame count / average fps gives 80 / (400/19) = 3.8 by luck here, but
        # any boundary in between would land on the wrong frame.
        assert shots[-1]["endTicks"] == 58368
        assert shots[0]["startTicks"] == 0


class TestShotsSubStage:
    """Sub-stage wiring: resumable, and keyed on the thresholds that shaped it."""

    def test_the_second_run_is_a_cache_hit(self, ctx: SubStageContext) -> None:
        first = run_shots_sub_stage(ctx, FADE_MP4)
        assert first.cache_hit is False
        assert run_shots_sub_stage(ctx, FADE_MP4).cache_hit is True

    def test_changing_a_threshold_invalidates_the_checkpoint(self, ctx: SubStageContext) -> None:
        # REQ-005: the thresholds ARE the model config. Serving a cached artefact
        # after a threshold change would report boundaries nobody asked for.
        run_shots_sub_stage(ctx, FADE_MP4)
        rerun = run_shots_sub_stage(ctx, FADE_MP4, config={"hard_cut_threshold": 15.0})
        assert rerun.cache_hit is False

    def test_the_artefact_is_written_and_reloadable(self, ctx: SubStageContext) -> None:
        result = run_shots_sub_stage(ctx, HARD_CUT_MP4)
        assert result.artefact_path.exists()
        assert len(result.artefact["shots"]) == 3

    def test_a_failure_leaves_the_sub_stage_resumable(self, ctx: SubStageContext, tmp_path: Path) -> None:
        junk = tmp_path / "broken.mp4"
        junk.write_bytes(b"nope")
        with pytest.raises(SubStageError):
            run_shots_sub_stage(ctx, junk)
        # No poisoned checkpoint: the real media must still be indexable.
        assert run_shots_sub_stage(ctx, HARD_CUT_MP4).cache_hit is False
