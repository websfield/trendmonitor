#: 1/15360 is the mp4 container timebase every fixture in this repo carries.
VIDEO_TIMEBASE = Timebase(num=1, den=15360)

ENGINE_STUB = {"name": "test", "version": "0", "parameters": []}


@functools.lru_cache(maxsize=None)
def _detected(media_path: Path) -> str:
    """Detection is deterministic, so each fixture is decoded once per session.

    Cached as canonical JSON rather than as the dict, so a test that mutates its
    copy cannot corrupt another test's fixture. `TestDetectionOnRealMedia`'s
    determinism case deliberately bypasses this and decodes twice for real.
    """
    return canonical_json(compute_shots(media_path))


def shots_for(media_path: Path) -> list[dict]:
    return json.loads(_detected(media_path))["shots"]



def probe(duration_ticks: int = 61440) -> VideoProbe:
    return VideoProbe(timebase=VIDEO_TIMEBASE, duration_ticks=duration_ticks, avg_frame_rate=Fraction(30))


