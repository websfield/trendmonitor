/**
 * Better Auth's rate-limit store (audit 2026-08-17 #20).
 *
 * Required because the limiter is configured with `storage: "database"` in
 * `packages/auth/src/create-auth.ts`, and the DEFAULT — `"memory"` — is not a
 * durable limiter for this deployment shape: an in-process counter resets on
 * every restart or redeploy and is not shared between instances, so "5 sign-in
 * attempts per minute" silently becomes "5 per minute per process".
 *
 * The shape is taken from the INSTALLED package, not from memory
 * (@better-auth/core 1.6.28, `db/get-tables.mjs`): model `rateLimit`, fields
 * `key` (string, unique, required), `count` (number, required), `lastRequest`
 * (number, bigint, required). The drizzle adapter resolves `schema.rateLimit`
 * and then each field by its JS property name, so these names are the contract
 * — renaming a property here breaks the limiter at runtime, not at compile time.
 *
 * `lastRequest` is a bigint because Better Auth stores epoch MILLISECONDS in it
 * (`defaultValue: () => Date.now()`), which overflows a 32-bit integer.
 */
export const rateLimit = pgTable("rate_limit", {
  id: text("id").primaryKey(),
  key: text("key").notNull().unique(),
  count: integer("count").notNull(),
  lastRequest: bigint("last_request", { mode: "number" }).notNull(),
});

export const userRelations = relations(user, ({ many }) => ({
  sessions: many(session),
  accounts: many(account),
}));

export const sessionRelations = relations(session, ({ one }) => ({
  user: one(user, {
    fields: [session.userId],
    references: [user.id],
  }),
}));

export const accountRelations = relations(account, ({ one }) => ({
  user: one(user, {
    fields: [account.userId],
    references: [user.id],
  }),
}));
